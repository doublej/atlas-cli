import { mkdir, writeFile } from 'node:fs/promises';
import { homedir } from 'node:os';
import { join } from 'node:path';
import type { Command } from '../types';
import { DEV_FOLDER } from '../template-discovery';

/** Single-quote a value for the generated zsh script. */
const zq = (s: string): string => `'${s.replaceAll("'", `'\\''`)}'`;

/** The `_atlas` completion function — commands from the registry, projects from the cache. */
function completionScript(cmds: { name: string; summary: string }[]): string {
	const rows = cmds.map((c) => `\t\t${zq(`${c.name}:${c.summary}`)}`).join('\n');
	return `#compdef atlas pj
# Generated by \`atlas install-autocompletion\` — rerun it after adding a command.

_atlas_projects() {
	(( $+commands[jq] )) || return 1
	[[ -r $ATLAS_CACHE ]] || return 1
	local -a names
	names=(\${(f)"$(jq -r '.projects[] | select(.archived != true) | .name' -- $ATLAS_CACHE 2>/dev/null)"})
	(( \${#names} )) && _describe -t projects 'project' names
}

_atlas() {
	local ATLAS_CACHE=${zq(join(DEV_FOLDER, '.atlas-cache.json'))}
	local -a cmds tree_cmds
	cmds=(
${rows}
	)
	tree_cmds=(
		'view:print the tree as ascii (--up: ancestors only)'
		'search:search every CLAUDE.md in the tree'
		'compose:concatenate the ancestor→project chain'
		'web:open the tree in the atlas web viewer'
	)

	# Past a --run, the rest is a command line for the shell — complete it as one.
	local ri=\${words[(i)--run]}
	if (( ri < CURRENT )); then
		shift $ri words
		(( CURRENT -= ri ))
		_normal
		return
	fi

	# \`pj\` is \`atlas jump\`: its first word is already the query.
	if [[ \${words[1]} == pj ]]; then
		_alternative 'projects:project:_atlas_projects' 'flags:flag:(--run)'
		return
	fi

	if (( CURRENT == 2 )); then
		_describe -t commands 'atlas command' cmds
		_atlas_projects   # \`atlas <query>\` searches when the word isn't a command
		return
	fi

	case \${words[2]} in
		tree)
			if (( CURRENT == 3 )); then
				_describe -t subcommands 'tree command' tree_cmds
			else
				_arguments '--up[only the chain towards the root]' '*:path:_files -/'
			fi
			;;
		jump|search)
			_alternative 'projects:project:_atlas_projects' 'flags:flag:(--run)'
			;;
	esac
}

_atlas "$@"
`;
}

/** Ask the login shell where completions are looked up. Empty when zsh isn't usable. */
async function zshFpath(): Promise<string[]> {
	const proc = Bun.spawn(['zsh', '-lc', 'print -l -- $fpath'], {
		stdout: 'pipe',
		stderr: 'ignore'
	});
	const out = await new Response(proc.stdout).text();
	if ((await proc.exited) !== 0) return [];
	return out.split('\n').filter(Boolean);
}

/**
 * `atlas install-autocompletion` — write the zsh completion for `atlas` and `pj` into a
 * directory that's already on `$fpath` (preferring `~/.zsh/completions`, as `_rig` does).
 */
export const installAutocompletion: Command = {
	name: 'install-autocompletion',
	summary: 'write the zsh completion for `atlas` and `pj` onto $fpath',
	async run() {
		const { COMMANDS } = await import('../registry');
		const home = homedir();
		const fpath = await zshFpath();
		const preferred = join(home, '.zsh', 'completions');
		const dir = fpath.includes(preferred)
			? preferred
			: (fpath.find((p) => p.startsWith(home)) ?? preferred);
		const target = join(dir, '_atlas');

		await mkdir(dir, { recursive: true });
		await writeFile(target, completionScript(COMMANDS));
		console.log(`wrote ${target} — completes \`atlas\` and \`pj\``);

		if (!fpath.includes(dir)) {
			console.log(`\n${dir} isn't on $fpath. Add above your compinit call in ~/.zshrc:`);
			console.log(`  fpath=(${dir} $fpath)`);
		}
		if (!Bun.which('jq')) {
			console.log('\njq not found — command completion works, project names need `brew install jq`.');
		}
		console.log('\nreload:  exec zsh');
		console.log('stale?   rm -f ~/.zcompdump* ~/.cache/zsh/zcompdump* && exec zsh');
	}
};
